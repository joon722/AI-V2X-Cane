def _page_number(canvas, doc):
    canvas.saveState()
    canvas.setFont("Malgun", 8)
    canvas.setFillColor(colors.HexColor("#888"))
    canvas.drawCentredString(A4[0] / 2, 11 * mm, str(doc.page))
    canvas.restoreState()


